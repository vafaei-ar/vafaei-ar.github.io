assert.equal(data.studies.stroke_carbon_2026.cleaner_grid_relocated_co2eq_tonnes_per_year,7408.68);
assert.equal(data.studies.pympute.metrics.length,11);
assert.equal(Math.min(...data.studies.pympute.metrics.map(x=>x.mape)),2.04);
assert.equal(Math.min(...data.studies.pympute.metrics.map(x=>x.rmse)),0.0025);
