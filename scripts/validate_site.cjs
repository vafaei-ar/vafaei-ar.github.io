"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const root=path.resolve(__dirname,"..");
const text=file=>fs.readFileSync(path.join(root,file),"utf8");
const html=text("index.html");
const data=JSON.parse(text("assets/research-results.json"));
const js=text("assets/research.js");
const css=text("assets/showcase.css");
const ids=Array.from(html.matchAll(/\bid="([^"]+)"/g),m=>m[1]);
assert.equal(ids.length,new Set(ids).size,"Duplicate HTML ids");
for(const [,target] of html.matchAll(/href="#([^"]+)"/g))assert.ok(ids.includes(target),"Broken anchor #"+target);
for(const file of ["profile-image.jpg","assets/research-results.json","assets/research.js","assets/showcase.css"]){
  assert.ok(fs.existsSync(path.join(root,file)),"Missing site asset: "+file);
}
assert.match(html,/Research in focus/);
assert.match(html,/data-demo-case="routine"/);
assert.match(html,/data-demo-case="followup"/);
assert.match(html,/data-demo-case="warning"/);
assert.match(html,/The Lancet Digital Health/);
assert.match(html,/Journal of the American Heart Association/);
assert.match(html,/Scientific Reports/);
assert.match(html,/Nature Communications/);
assert.ok(!html.includes("ai-sonar-economic-model"),"Private repo must not be linked");
assert.equal(data.studies.sustainable_ai.fold_lower_modeled_co2eq,147);
assert.equal(data.studies.stroke_carbon_2026.reported_relative_reduction_percent,54.75);
